"""Generate src/data/metrobus.ts from the IETT GTFS feed.

Download the feed (data.ibb.gov.tr, dataset "iett-gtfs-verisi") into one
folder; stop_times may be the .csv or the unzipped stop_times.txt. Then run:

    python3 scripts/import-metrobus.py <gtfs-folder>

Only the 34G pattern is used: it runs the whole corridor, Beylikdüzü Sondurak
to Söğütlüçeşme. The feed gives times at the two termini only, so the run time
between stops is estimated: the trip time is split by distance after a fixed
dwell per stop. The app marks the line as estimated and does not draw buses.

The feed is UTF-8 but route names are double-encoded, and its coordinates have
lost their decimal point ("410.191.700.005.564" is 41.0191700005564).
"""

import csv
import math
import statistics
import sys
from collections import defaultdict
from pathlib import Path

LINE = '34G'
FORWARD, BACKWARD = '0', '1'  # 0: Beylikdüzü → Söğütlüçeşme
COLOR = '#B5654A'
DWELL = 30
NIGHT_CUTOFF = 3 * 3600
DAYS = {'weekday': 'monday', 'saturday': 'saturday', 'sunday': 'sunday'}
NAMES = {
    'B.SONDURAK': 'Beylikdüzü Sondurak',
    'B.BELEDİYE': 'Beylikdüzü Belediye',
    'H.SANAYİ': 'Haramidere Sanayi',
    'CİHANGİR - ÜNİV.MAH.': 'Cihangir – Üniversite Mahallesi',
    'AVCILAR MRK.ÜNV.KMP.': 'Avcılar Merkez Üniversite Kampüsü',
    'İBB SOSYAL TESİSLERİ': 'İBB Sosyal Tesisleri',
    'BAYRAMPAŞA - MALTEPE / KOÇ ÜNİVERSİTESİ HASTANESİ': 'Bayrampaşa – Maltepe',
}


def read(folder: Path, name: str):
    path = folder / f'{name}.csv'
    if not path.exists():
        path = folder / f'{name}.txt'
    with open(path, encoding='utf-8-sig', errors='replace', newline='') as handle:
        sample = handle.readline()
        handle.seek(0)
        yield from csv.DictReader(handle, delimiter=';' if ';' in sample else ',')


def coordinate(value: str) -> float:
    digits = value.replace('.', '').rstrip(';')
    return float(f'{digits[:2]}.{digits[2:]}')


def seconds(value: str) -> int:
    h, m, s = (int(part) for part in value.split(':'))
    return h * 3600 + m * 60 + s


def haversine_km(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (a[1], a[0], b[1], b[0]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * 6371 * math.asin(min(1, math.sqrt(h)))


def title(name: str) -> str:
    if name.strip() in NAMES:
        return NAMES[name.strip()]
    words = name.strip().replace(' - ', ' – ').split(' ')
    return ' '.join(w[:1] + w[1:].replace('I', 'ı').replace('İ', 'i').lower() if w.isupper() else w for w in words)


def main(folder: Path):
    route_ids = {r['route_id'] for r in read(folder, 'routes') if r['route_short_name'] == LINE}
    calendar = {c['service_id']: c for c in read(folder, 'calendar')}
    trips = {t['trip_id']: t for t in read(folder, 'trips') if t['route_id'] in route_ids}
    times = defaultdict(list)
    for row in read(folder, 'stop_times'):
        if row['trip_id'] in trips:
            times[row['trip_id']].append(row)
    stops = {s['stop_id']: s for s in read(folder, 'stops')}

    full = {}
    for direction in (FORWARD, BACKWARD):
        candidates = [t for t in trips if trips[t]['direction_id'] == direction]
        longest = max(len(times[t]) for t in candidates)
        full[direction] = [t for t in candidates if len(times[t]) == longest]
    sequence = [r['stop_id'] for r in sorted(times[full[FORWARD][0]], key=lambda r: int(r['stop_sequence']))]
    point = lambda s: (coordinate(stops[s]['stop_lon']), coordinate(stops[s]['stop_lat']))
    ids = [f'mb{s}' for s in sequence]

    trip_time = statistics.median(
        seconds(rows[-1]['arrival_time']) - seconds(rows[0]['arrival_time'])
        for rows in (sorted(times[t], key=lambda r: int(r['stop_sequence'])) for t in full[FORWARD])
    )
    gaps = [haversine_km(point(a), point(b)) for a, b in zip(sequence, sequence[1:])]
    moving = trip_time - DWELL * len(gaps)
    run_times = [round(DWELL + moving * gap / sum(gaps)) for gap in gaps]

    departures = {}
    for direction in (FORWARD, BACKWARD):
        departures[direction] = {}
        for day, flag in DAYS.items():
            starts = set()
            for trip in full[direction]:
                if calendar[trips[trip]['service_id']][flag] != '1':
                    continue
                first = min(times[trip], key=lambda r: int(r['stop_sequence']))
                start = seconds(first['departure_time'] or first['arrival_time'])
                starts.add(start + 86400 if start < NIGHT_CUTOFF else start)
            departures[direction][day] = sorted(starts)

    out_path = Path(__file__).resolve().parent.parent / 'src/data/metrobus.ts'
    with open(out_path, 'w', encoding='utf-8') as out:
        out.write('// Generated by scripts/import-metrobus.py from the IETT GTFS feed (34G). Do not edit.\n')
        out.write(f'// Run times are estimated: {round(trip_time / 60)} min end to end, split by distance after a {DWELL} s dwell per stop.\n')
        out.write("import type { InterStationTime, Line, Route, Station } from '../types';\n\n")
        out.write('export const metrobusLine: Line = {\n')
        out.write(f"  id: 'MB', code: 'MB', name: 'Beylikdüzü – Söğütlüçeşme', mode: 'bus', color: '{COLOR}', estimated: true,\n")
        out.write(f"  stationIds: [{', '.join(repr(s) for s in ids)}],\n}};\n\n")

        out.write('export const metrobusStations: Station[] = [\n')
        distance = 0.0
        for index, stop_id in enumerate(sequence):
            if index:
                distance += gaps[index - 1]
            lon, lat = point(stop_id)
            name = title(stops[stop_id]['stop_name'])
            out.write(f"  {{ id: '{ids[index]}', name: '{name}', coordinates: [{lon:.6f}, {lat:.6f}], distanceFromStart: {distance:.2f}, lineId: 'MB' }},\n")
        out.write('];\n\n')

        out.write('export const metrobusInterStationTimes: InterStationTime[] = [\n')
        for a, b, t in zip(ids, ids[1:], run_times):
            out.write(f"  {{ fromStationId: '{a}', toStationId: '{b}', time: {t} }},\n")
        out.write('];\n\n')

        out.write('export const metrobusRoutes: Route[] = [\n  {\n')
        out.write("    id: 'mb',\n    lineId: 'MB',\n    nameKey: '',\n    shortNameKey: 'mode.bus',\n")
        out.write(f"    termini: ['{ids[0]}', '{ids[-1]}'],\n")
        out.write(f"    stations: [{', '.join(repr(s) for s in ids)}],\n")
        out.write(f"    color: '{COLOR}',\n    service: {{\n")
        for key, direction in (('forward', FORWARD), ('backward', BACKWARD)):
            out.write(f"      {key}: {{\n        kind: 'timetable',\n        departures: {{\n")
            for day in DAYS:
                out.write(f"          {day}: [{', '.join(str(v) for v in departures[direction][day])}],\n")
            out.write('        },\n      },\n')
        out.write('    },\n  },\n];\n')
    print(f'{len(ids)} stops, {round(trip_time / 60)} min, departures', {d: len(v) for d, v in departures[FORWARD].items()})


if __name__ == '__main__':
    main(Path(sys.argv[1]))
